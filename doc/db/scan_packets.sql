-- =========================================
-- 4) Packet intake function
-- =========================================
-- One INSERT for the header + one INSERT for all child rows, inside one
-- function = one implicit transaction: any failure rolls back both (atomicity,
-- tickets/121 §8). author_id/type_code in payload are set by the Edge
-- Function, not taken from the client request body as-is - this function
-- does not authenticate the caller itself, that already happened at the Edge
-- Function level, which calls this function via the service_role client.
CREATE OR REPLACE FUNCTION submit_scan_packet(payload jsonb)
RETURNS TABLE(packet_id bigint, created boolean) AS $$
DECLARE
  v_packet_id bigint;
  v_client_packet_id uuid := (payload->>'client_packet_id')::uuid;
BEGIN
  INSERT INTO scan_packets (
    client_packet_id, type, author_id, bus_id, group_id,
    date, started_at, finished_at, children_count
  )
  VALUES (
    v_client_packet_id,
    (payload->>'type_code')::smallint,
    (payload->>'author_id')::bigint,
    NULLIF(payload->>'bus_id', '')::smallint,
    NULLIF(payload->>'group_id', '')::smallint,
    payload->>'date',
    NULLIF(payload->>'started_at', '')::timestamptz,
    (payload->>'finished_at')::timestamptz,
    jsonb_array_length(COALESCE(payload->'children', '[]'::jsonb))
  )
  ON CONFLICT (client_packet_id) DO NOTHING
  RETURNING id INTO v_packet_id;

  IF v_packet_id IS NULL THEN
    -- Already exists: either a retry after a lost response, or a race between
    -- two simultaneous retries (either way - do not create again).
    SELECT id INTO v_packet_id FROM scan_packets WHERE client_packet_id = v_client_packet_id;
    RETURN QUERY SELECT v_packet_id, false;
    RETURN;
  END IF;

  INSERT INTO scans (date, user_id, child_id, bus_id, type, packet_id, method, created_at)
  SELECT
    payload->>'date',
    (payload->>'author_id')::bigint,
    (c->>'child_id')::bigint,
    NULLIF(payload->>'bus_id', '')::smallint,
    1,
    v_packet_id,
    CASE WHEN c->>'method' = 'MANUAL' THEN 2 ELSE 1 END,
    COALESCE(NULLIF(c->>'timestamp', '')::timestamptz, now())
  FROM jsonb_array_elements(COALESCE(payload->'children', '[]'::jsonb)) AS c;

  RETURN QUERY SELECT v_packet_id, true;
END;
$$ LANGUAGE plpgsql;

-- =========================================
-- 5) RLS for scan_packets
-- =========================================
ALTER TABLE public.scan_packets ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "scan_packets_select_authenticated" ON public.scan_packets;
CREATE POLICY "scan_packets_select_authenticated"
  ON public.scan_packets FOR SELECT
  TO authenticated
  USING (true);

-- No INSERT/UPDATE/DELETE policy for authenticated is created on purpose:
-- writes happen only through submit_scan_packet(), called by the
-- submit-scan-packet Edge Function via the service_role client, which RLS
-- does not apply to. Do NOT add a permissive "just in case" write policy
-- here - see vault/03-База-данных/RLS-политики.md, "Неотозванные широкие
-- legacy-политики", for why that pattern has already made a narrower policy
-- meaningless elsewhere in this project (children_today/groups_today/
-- reset_events/children/days).

